/** Font size in output pixels, mirroring `overlayRender.drawOverlay`. */
export const overlayFontSize = (overlay: ClipOverlay, height: number): number =>
  Math.max(4, Math.round((overlay.fontSize / 100) * height * Math.max(0.05, overlay.scale)));

/** On-screen width of an image overlay, mirroring `overlayRender.drawOverlay`. */
export const overlayImageWidth = (overlay: ClipOverlay, width: number): number =>
  Math.max(2, Math.round(width * IMAGE_BASE_WIDTH * Math.max(0.05, overlay.scale)));

/** Bounding box of a rotated rectangle (ffmpeg's `rotate` grows the frame). */
export const rotatedSize = (
  width: number,
  height: number,
  degrees: number
): { width: number; height: number } => {
  const radians = (degrees * Math.PI) / 180;
  const cos = Math.abs(Math.cos(radians));
  const sin = Math.abs(Math.sin(radians));
  return {
    width: Math.max(2, Math.round(width * cos + height * sin)),
    height: Math.max(2, Math.round(height * cos + width * sin))
  };
};

/**
 * Alpha of an overlay as an ffmpeg expression of `t` (seconds into the clip).
 * Mirrors `overlayRender.getOverlayAlpha`: opacity with linear fade in/out.
 */
export const buildOverlayAlphaExpression = (overlay: ClipOverlay): string => {
  const { start, end } = getOverlayRange(overlay);
  const span = Math.max(0, end - start);
  const fade = Math.max(0, Math.min(overlay.fadeDuration, span / 2));
  const opacity = clamp01(overlay.opacity);

  if (fade <= 0 || span <= 0) return num(opacity);

  const fadeIn = `${num(opacity)}*(t-${num(start)})/${num(fade)}`;
  const fadeOut = `${num(opacity)}*(${num(end)}-t)/${num(fade)}`;
  return (
    `if(lt(t,${num(start)}),0,` +
    `if(lt(t,${num(start + fade)}),${fadeIn},` +
    `if(lt(t,${num(end - fade)}),${num(opacity)},` +
    `if(lt(t,${num(end)}),${fadeOut},0))))`
  );
};

/** `enable=` window for an overlay. */
export const buildOverlayEnableExpression = (overlay: ClipOverlay): string => {
  const { start, end } = getOverlayRange(overlay);
  return `between(t,${num(start)},${num(end)})`;
};


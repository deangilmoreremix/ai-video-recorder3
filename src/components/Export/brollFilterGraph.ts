/**
 * How the editor's transitions are baked with ffmpeg's `xfade` filter.
 *
 * | store type    | xfade      | why                                          |
 * | ------------- | ---------- | -------------------------------------------- |
 * | `fade`        | fade       | straight cross fade                           |
 * | `dissolve`    | dissolve   | noise-driven dissolve, matches the preview    |
 * | `slide-left`  | slideleft  | 1:1                                           |
 * | `slide-right` | slideright | 1:1                                           |
 * | `slide-up`    | slideup    | 1:1                                           |
 * | `slide-down`  | slidedown  | 1:1                                           |
 * | `wipe`        | wipeleft   | the preview wipes left→right revealing the new clip |
 * | `cross-zoom`  | zoomin     | closest zoom based transition xfade ships     |
 * | `rotate`      | radial     | xfade has no rotation; `radial` is the only sweep that rotates around the centre |
 */
export const TRANSITION_TO_XFADE: Record<TransitionType, string> = {
  fade: 'fade',
  dissolve: 'dissolve',
  'slide-left': 'slideleft',
  'slide-right': 'slideright',
  'slide-up': 'slideup',
  'slide-down': 'slidedown',
  wipe: 'wipeleft',
  'cross-zoom': 'zoomin',
  rotate: 'radial'
};

/** xfade refuses zero length transitions. */
export const MIN_TRANSITION_DURATION = 0.1;
/** A transition may never eat more than this share of either neighbour. */
const MAX_TRANSITION_SHARE = 0.9;

export const xfadeTransition = (type: TransitionType | undefined): string =>
  (type && TRANSITION_TO_XFADE[type]) || TRANSITION_TO_XFADE.fade;

/* -------------------------------------------------------------------------- */
/*  Formatting helpers                                                        */
/* -------------------------------------------------------------------------- */

const clamp = (value: number, min: number, max: number, fallback = min): number => {
  if (!Number.isFinite(value)) return fallback;
  return Math.min(max, Math.max(min, value));
};

const clamp01 = (value: number): number => clamp(value, 0, 1, 0);

/** Compact, locale independent number for a filter argument. */
export const num = (value: number, decimals = 3): string => {
  if (!Number.isFinite(value)) return '0';
  const factor = 10 ** decimals;
  return String(Math.round(value * factor) / factor);
};

const evenPixels = (value: number, fallback: number): number => {
  const rounded = Math.round(Number.isFinite(value) && value > 0 ? value : fallback);
  const clamped = Math.min(3840, Math.max(16, rounded));
  return clamped % 2 === 0 ? clamped : clamped - 1;
};

/**
 * Quotes for the filter-graph parser. Quotes/backslashes are dropped rather
 * than escaped: no value we build legitimately contains them, and dropping is
 * the only way to guarantee the graph cannot be broken out of.
 */
export const quoteFilterValue = (value: string): string => `'${value.replace(/['\\]/g, '')}'`;

/** MEMFS names are generated by us, this only guards against odd clip names. */
export const safeFileName = (value: string): string => value.replace(/[^a-zA-Z0-9._-]/g, '_');

/** `#rgb` / `#rrggbb` / `0xrrggbb` → the `0xRRGGBB` form ffmpeg understands. */
export const toFFmpegColor = (value: string | null | undefined, fallback = '0x000000'): string => {
  if (!value) return fallback;
  const raw = value.trim().replace(/^#/, '').replace(/^0x/i, '');
  if (/^[0-9a-f]{3}$/i.test(raw)) {
    const [r, g, b] = raw.split('');
    return `0x${r}${r}${g}${g}${b}${b}`.toUpperCase().replace('0X', '0x');
  }
  if (/^[0-9a-f]{6}$/i.test(raw)) return `0x${raw.toUpperCase()}`;
  if (/^[0-9a-f]{8}$/i.test(raw)) return `0x${raw.slice(0, 6).toUpperCase()}`;
  return fallback;
};

const withAlpha = (color: string, alpha: number): string => `${color}@${num(clamp01(alpha))}`;


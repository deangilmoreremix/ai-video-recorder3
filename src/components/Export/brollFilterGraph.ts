export interface TimelineSegment {
  /** MEMFS path of the normalised clip produced by `buildClipPassArgs`. */
  file: string;
  duration: number;
  /** How this segment enters from the previous one. `null` = hard cut. */
  transition?: { type: TransitionType; duration: number } | null;
}

export interface TimelineTransitionPlan {
  /** Index of the incoming segment. */
  index: number;
  xfade: string;
  duration: number;
  offset: number;
}

export interface TimelinePlan {
  transitions: TimelineTransitionPlan[];
  totalDuration: number;
}

/**
 * Works out the xfade offsets. Each transition overlaps the two neighbouring
 * clips, so the timeline shortens by the transition duration every time.
 */
export const planTimeline = (segments: TimelineSegment[]): TimelinePlan => {
  const transitions: TimelineTransitionPlan[] = [];
  if (segments.length === 0) return { transitions, totalDuration: 0 };

  let total = Math.max(0.05, segments[0].duration);

  for (let index = 1; index < segments.length; index += 1) {
    const segment = segments[index];
    const segmentDuration = Math.max(0.05, segment.duration);
    const requested = segment.transition?.duration ?? 0;

    const maxDuration = Math.min(total, segmentDuration) * MAX_TRANSITION_SHARE;
    const duration = segment.transition
      ? clamp(requested, MIN_TRANSITION_DURATION, Math.max(MIN_TRANSITION_DURATION, maxDuration), MIN_TRANSITION_DURATION)
      : 0;

    if (duration > 0) {
      transitions.push({
        index,
        xfade: xfadeTransition(segment.transition?.type),
        duration,
        offset: Math.max(0, total - duration)
      });
    }

    total = total + segmentDuration - duration;
  }

  return { transitions, totalDuration: total };
};

export interface TimelinePassOptions {
  output: string;
  crf?: number;
  preset?: string;
  audioBitrate?: number;
  fastStart?: boolean;
}

export interface TimelinePass {
  args: string[];
  totalDuration: number;
}

/**
 * Joins the normalised clips into the final video, cross fading video with
 * `xfade` and audio with `acrossfade` so both stay in sync.
 */
export const buildTimelinePassArgs = (
  segments: TimelineSegment[],
  options: TimelinePassOptions
): TimelinePass => {
  if (segments.length < 2) {
    throw new Error('The timeline pass needs at least two clips.');
  }

  const plan = planTimeline(segments);
  const byIndex = new Map(plan.transitions.map((transition) => [transition.index, transition]));

  const chains: string[] = [];
  let videoLabel = '[0:v]';
  let audioLabel = '[0:a]';

  for (let index = 1; index < segments.length; index += 1) {
    const transition = byIndex.get(index);
    const nextVideo = `[vx${index}]`;
    const nextAudio = `[ax${index}]`;

    if (transition) {
      chains.push(
        `${videoLabel}[${index}:v]xfade=transition=${transition.xfade}:` +
          `duration=${num(transition.duration)}:offset=${num(transition.offset)}${nextVideo}`
      );
      chains.push(
        `${audioLabel}[${index}:a]acrossfade=d=${num(transition.duration)}:c1=tri:c2=tri${nextAudio}`
      );
    } else {
      // Hard cut: concat keeps the same labelling so the chain stays uniform.
      chains.push(
        `${videoLabel}${audioLabel}[${index}:v][${index}:a]concat=n=2:v=1:a=1${nextVideo}${nextAudio}`
      );
    }

    videoLabel = nextVideo;
    audioLabel = nextAudio;
  }

  const inputs = segments.flatMap((segment) => ['-i', segment.file]);
  const crf = Math.round(clamp(options.crf ?? 20, 0, 51, 20));
  const audioBitrate = Math.round(clamp(options.audioBitrate ?? 192, 32, 512, 192));

  const args = [
    '-nostdin',
    ...inputs,
    '-filter_complex',
    chains.join(';'),
    '-map',
    videoLabel,
    '-map',
    audioLabel,
    '-c:v',
    'libx264',
    '-preset',
    options.preset ?? 'veryfast',
    '-crf',
    String(crf),
    '-pix_fmt',
    'yuv420p',
    '-c:a',
    'aac',
    '-b:a',
    `${audioBitrate}k`,
    '-ar',
    '44100',
    '-ac',
    '2'
  ];

  if (options.fastStart !== false) args.push('-movflags', '+faststart');
  args.push(options.output);

  return { args, totalDuration: plan.totalDuration };
};

/** Probe used to find out whether a source really carries an audio stream. */
export const buildAudioProbeArgs = (file: string): string[] => [
  '-nostdin',
  '-hide_banner',
  '-i',
  file,
  '-map',
  '0:a:0',
  '-t',
  '0.05',
  '-f',
  'null',
  '-'
];

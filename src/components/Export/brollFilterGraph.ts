/**
 * Pure ffmpeg filter-graph / argument builders for the B-Roll export.
 *
 * Everything in this module is side-effect free and DOM free: it turns the
 * B-Roll store data (clips, backgrounds, overlays, transitions) into ffmpeg
 * command lines. `brollCompositor.ts` feeds the results to ffmpeg.wasm.
 *
 * Keeping the string building here means the whole graph can be built (and
 * asserted on) without a browser - see `scripts/check-broll-filtergraph.mjs`.
 */
import type { BRollClip, ClipBackground, ClipOverlay, TransitionType } from '../../store/brollStore';
import { IMAGE_BASE_WIDTH, getOverlayRange } from '../Editor/BRoll/Overlays/overlayRender';


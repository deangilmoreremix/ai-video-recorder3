export interface TextOverlayRender {
  kind: 'text';
  overlay: ClipOverlay;
  /** MEMFS path holding the text (keeps user text out of the filter graph). */
  textFile: string;
  /** MEMFS path of the TrueType font drawtext renders with. */
  fontFile: string;
}

export interface ImageOverlayRender {
  kind: 'image';
  overlay: ClipOverlay;
  /** MEMFS path of the decoded overlay image. */
  file: string;
  /** Natural pixel size of the image, used to keep its aspect ratio. */
  naturalWidth: number;
  naturalHeight: number;
}

export type OverlayRender = TextOverlayRender | ImageOverlayRender;

export interface BRollClipPassRequest {
  /** Output frame size - identical for every clip so xfade can chain them. */
  width: number;
  height: number;
  fps: number;
  /** How long this clip lasts inside the sequence, in seconds. */
  duration: number;
  source: {
    file: string;
    /** Images are looped for `duration` seconds instead of decoded as video. */
    still: boolean;
    /** Seconds skipped at the head of the source. */
    trimStart?: number;
    /** The source carries an audio stream we should keep. */
    hasAudio?: boolean;
  };
  background?: ClipBackground | null;
  /** MEMFS path of the background image (only used when mode === 'image'). */
  backgroundFile?: string | null;
  overlays?: OverlayRender[];
  colorFilters?: BRollClip['filters'];
  volume?: number;
  /** Fade in from black/silence at the head of the clip, in seconds. */
  fadeIn?: number;
  output: string;
  /** x264 CRF for the intermediate file. */
  crf?: number;
  preset?: string;
}

/** Image fit chain shared by background images. */
const imageFitChain = (fit: ClipBackground['imageFit'], width: number, height: number): string => {
  switch (fit) {
    case 'contain':
      return (
        `scale=${width}:${height}:force_original_aspect_ratio=decrease,` +
        `pad=${width}:${height}:(ow-iw)/2:(oh-ih)/2:color=black`
      );
    case 'stretch':
      return `scale=${width}:${height}`;
    case 'cover':
    default:
      return `scale=${width}:${height}:force_original_aspect_ratio=increase,crop=${width}:${height}`;
  }
};

interface InputArgs {
  args: string[];
  /** ffmpeg input index of every declared input. */
  sourceIndex: number;
  backgroundIndex: number | null;
  overlayIndexes: number[];
  silenceIndex: number;
}

const buildInputArgs = (request: BRollClipPassRequest): InputArgs => {
  const args: string[] = [];
  const duration = Math.max(0.05, request.duration);
  const fps = clamp(request.fps, 1, 120, 30);
  let index = 0;

  // 0: the clip itself.
  if (request.source.still) {
    args.push('-loop', '1', '-framerate', num(fps), '-t', num(duration), '-i', request.source.file);
  } else {
    const trimStart = Math.max(0, request.source.trimStart ?? 0);
    if (trimStart > 0) args.push('-ss', num(trimStart));
    args.push('-t', num(duration), '-i', request.source.file);
  }
  const sourceIndex = index;
  index += 1;

  // 1: background image (still, looped so it lasts the whole clip).
  let backgroundIndex: number | null = null;
  if (request.background?.mode === 'image' && request.backgroundFile) {
    args.push('-loop', '1', '-framerate', num(fps), '-t', num(duration), '-i', request.backgroundFile);
    backgroundIndex = index;
    index += 1;
  }

  // 2..n: overlay images (looped so `fade` can animate their alpha over time).
  const overlayIndexes: number[] = [];
  for (const overlay of request.overlays ?? []) {
    if (overlay.kind !== 'image') {
      overlayIndexes.push(-1);
      continue;
    }
    args.push('-loop', '1', '-framerate', num(fps), '-t', num(duration), '-i', overlay.file);
    overlayIndexes.push(index);
    index += 1;
  }

  // last: silence, used whenever the clip has no audio of its own so every
  // normalised clip can be joined with `acrossfade`.
  args.push(
    '-f',
    'lavfi',
    '-t',
    num(duration),
    '-i',
    'anullsrc=channel_layout=stereo:sample_rate=44100'
  );
  const silenceIndex = index;

  return { args, sourceIndex, backgroundIndex, overlayIndexes, silenceIndex };
};

/**
 * Background compositing.
 *
 * IMPORTANT LIMITATION: ffmpeg.wasm cannot run person segmentation, so the
 * background is *not* replaced around a segmented subject the way the live
 * preview does. Instead the chosen colour / blur plate / image is rendered as a
 * full-frame backdrop and the clip is fitted on top of it, so it shows wherever
 * the clip does not cover the frame (letterbox / pillarbox areas).
 */
const buildBackgroundChain = (
  request: BRollClipPassRequest,
  inputs: InputArgs
): { chains: string[]; label: string } => {
  const width = evenPixels(request.width, 1280);
  const height = evenPixels(request.height, 720);
  const fps = clamp(request.fps, 1, 120, 30);
  const duration = Math.max(0.05, request.duration);
  const fit = `scale=${width}:${height}:force_original_aspect_ratio=decrease,setsar=1`;
  const source = `[${inputs.sourceIndex}:v]`;
  const mode = request.background?.mode ?? 'none';
  const chains: string[] = [];

  if (mode === 'color') {
    const color = toFFmpegColor(request.background?.color, '0x000000');
    chains.push(`color=c=${color}:s=${width}x${height}:r=${num(fps)}:d=${num(duration)},setsar=1[bgplate]`);
    chains.push(`${source}fps=${fps},${fit}[bgfg]`);
    chains.push('[bgplate][bgfg]overlay=(W-w)/2:(H-h)/2:shortest=1[bgout]');
    return { chains, label: '[bgout]' };
  }

  if (mode === 'blur') {
    // Radius has to stay well inside the frame or boxblur refuses to run.
    const maxRadius = Math.max(1, Math.floor(Math.min(width, height) / 2) - 1);
    const radius = Math.round(clamp(request.background?.blurAmount ?? 12, 1, maxRadius, 12));
    chains.push(`${source}fps=${fps},split=2[bgsrc][fgsrc]`);
    chains.push(
      `[bgsrc]scale=${width}:${height}:force_original_aspect_ratio=increase,crop=${width}:${height},` +
        `boxblur=luma_radius=${radius}:luma_power=2:chroma_radius=${radius}:chroma_power=2,setsar=1[bgplate]`
    );
    chains.push(`[fgsrc]${fit}[bgfg]`);
    chains.push('[bgplate][bgfg]overlay=(W-w)/2:(H-h)/2:shortest=1[bgout]');
    return { chains, label: '[bgout]' };
  }

  if (mode === 'image' && inputs.backgroundIndex !== null) {
    const fitChain = imageFitChain(request.background?.imageFit ?? 'cover', width, height);
    chains.push(`[${inputs.backgroundIndex}:v]fps=${fps},${fitChain},setsar=1[bgplate]`);
    chains.push(`${source}fps=${fps},${fit}[bgfg]`);
    chains.push('[bgplate][bgfg]overlay=(W-w)/2:(H-h)/2:shortest=1[bgout]');
    return { chains, label: '[bgout]' };
  }

  // 'none' (and 'image' without a usable picture): plain letterbox on black.
  chains.push(
    `${source}fps=${fps},${fit},pad=${width}:${height}:(ow-iw)/2:(oh-ih)/2:color=black[bgout]`
  );
  return { chains, label: '[bgout]' };
};

const buildColorFilterChain = (filters: BRollClip['filters'] | undefined): string[] => {
  if (!filters) return [];
  const parts: string[] = [];
  const brightness = clamp(filters.brightness ?? 1, 0, 3, 1) - 1;
  const contrast = clamp(filters.contrast ?? 1, 0, 3, 1);
  const saturation = clamp(filters.saturation ?? 1, 0, 3, 1);

  if (Math.abs(brightness) > 0.001 || Math.abs(contrast - 1) > 0.001 || Math.abs(saturation - 1) > 0.001) {
    parts.push(
      `eq=brightness=${num(clamp(brightness, -1, 1, 0))}:contrast=${num(contrast)}:saturation=${num(saturation)}`
    );
  }

  const blur = clamp(filters.blur ?? 0, 0, 50, 0);
  if (blur >= 1) {
    const radius = Math.round(blur);
    parts.push(`boxblur=luma_radius=${radius}:luma_power=1:chroma_radius=${radius}:chroma_power=1`);
  }

  return parts;
};

const buildTextOverlayFilter = (
  render: TextOverlayRender,
  width: number,
  height: number
): string => {
  const { overlay } = render;
  const fontSize = overlayFontSize(overlay, height);
  const centerX = Math.round(clamp01(overlay.position.x) * width);
  const centerY = Math.round(clamp01(overlay.position.y) * height);

  const options = [
    `fontfile=${quoteFilterValue(render.fontFile)}`,
    `textfile=${quoteFilterValue(render.textFile)}`,
    'reload=0',
    `fontsize=${fontSize}`,
    `fontcolor=${toFFmpegColor(overlay.color, '0xFFFFFF')}`,
    `x=${quoteFilterValue(`${centerX}-text_w/2`)}`,
    `y=${quoteFilterValue(`${centerY}-text_h/2`)}`,
    `line_spacing=${Math.round(fontSize * 0.15)}`,
    `alpha=${quoteFilterValue(buildOverlayAlphaExpression(overlay))}`,
    `enable=${quoteFilterValue(buildOverlayEnableExpression(overlay))}`
  ];

  if (overlay.backgroundColor) {
    options.push(
      'box=1',
      `boxcolor=${toFFmpegColor(overlay.backgroundColor, '0x000000')}`,
      `boxborderw=${Math.max(1, Math.round(fontSize * 0.35))}`
    );
  }

  if (overlay.fontWeight === 'bold') {
    // Only the regular weight is bundled, so bold is faked with a border in the
    // text colour - visually very close to a real bold face at overlay sizes.
    options.push(
      `borderw=${Math.max(1, Math.round(fontSize * 0.035))}`,
      `bordercolor=${toFFmpegColor(overlay.color, '0xFFFFFF')}`
    );
  }

  if (overlay.shadow) {
    options.push(
      `shadowcolor=${withAlpha('0x000000', 0.6)}`,
      `shadowx=${Math.max(1, Math.round(fontSize * 0.04))}`,
      `shadowy=${Math.max(1, Math.round(fontSize * 0.06))}`
    );
  }

  return `drawtext=${options.join(':')}`;
};

const buildImageOverlayChain = (
  render: ImageOverlayRender,
  inputIndex: number,
  label: string,
  width: number,
  height: number
): { chain: string; x: number; y: number } => {
  const { overlay } = render;
  const drawWidth = overlayImageWidth(overlay, width);
  const ratio =
    render.naturalWidth > 0 && render.naturalHeight > 0
      ? render.naturalHeight / render.naturalWidth
      : 9 / 16;
  const drawHeight = Math.max(2, Math.round(drawWidth * ratio));

  const parts = [`scale=${drawWidth}:${drawHeight}`, 'format=rgba'];

  const rotation = Number.isFinite(overlay.rotation) ? overlay.rotation : 0;
  let boxWidth = drawWidth;
  let boxHeight = drawHeight;
  if (Math.abs(rotation) > 0.01) {
    const box = rotatedSize(drawWidth, drawHeight, rotation);
    boxWidth = box.width;
    boxHeight = box.height;
    // ffmpeg rotates clockwise for positive angles, same as the canvas preview.
    parts.push(
      `rotate=${num((rotation * Math.PI) / 180, 5)}:c=none:ow=${boxWidth}:oh=${boxHeight}`
    );
  }

  const { start, end } = getOverlayRange(overlay);
  const span = Math.max(0, end - start);
  const fade = Math.max(0, Math.min(overlay.fadeDuration, span / 2));
  parts.push(`colorchannelmixer=aa=${num(clamp01(overlay.opacity))}`);
  if (fade > 0) {
    parts.push(`fade=t=in:st=${num(start)}:d=${num(fade)}:alpha=1`);
    parts.push(`fade=t=out:st=${num(end - fade)}:d=${num(fade)}:alpha=1`);
  }

  return {
    chain: `[${inputIndex}:v]${parts.join(',')}${label}`,
    x: Math.round(clamp01(overlay.position.x) * width - boxWidth / 2),
    y: Math.round(clamp01(overlay.position.y) * height - boxHeight / 2)
  };
};

/**
 * Builds the complete ffmpeg command that renders ONE clip with its background
 * and overlays baked in, normalised to the sequence's frame size / fps and with
 * a guaranteed stereo audio track.
 */
export const buildClipPassArgs = (request: BRollClipPassRequest): string[] => {
  const width = evenPixels(request.width, 1280);
  const height = evenPixels(request.height, 720);
  const duration = Math.max(0.05, request.duration);
  const inputs = buildInputArgs(request);

  const chains: string[] = [];
  const background = buildBackgroundChain(request, inputs);
  chains.push(...background.chains);

  let videoLabel = background.label;
  let step = 0;

  const colorFilters = buildColorFilterChain(request.colorFilters);
  if (colorFilters.length > 0) {
    step += 1;
    const next = `[cf${step}]`;
    chains.push(`${videoLabel}${colorFilters.join(',')}${next}`);
    videoLabel = next;
  }

  (request.overlays ?? []).forEach((overlay, index) => {
    if (!overlay.overlay.visible) return;
    step += 1;

    if (overlay.kind === 'text') {
      const next = `[ov${step}]`;
      chains.push(`${videoLabel}${buildTextOverlayFilter(overlay, width, height)}${next}`);
      videoLabel = next;
      return;
    }

    const inputIndex = inputs.overlayIndexes[index];
    if (inputIndex === undefined || inputIndex < 0) return;

    const layer = `[ovsrc${step}]`;
    const next = `[ov${step}]`;
    const built = buildImageOverlayChain(overlay, inputIndex, layer, width, height);
    chains.push(built.chain);
    chains.push(
      `${videoLabel}${layer}overlay=${built.x}:${built.y}:` +
        `enable=${quoteFilterValue(buildOverlayEnableExpression(overlay.overlay))}${next}`
    );
    videoLabel = next;
  });

  const fadeIn = clamp(request.fadeIn ?? 0, 0, Math.max(0, duration / 2), 0);
  const tail = ['format=yuv420p'];
  if (fadeIn > 0) tail.unshift(`fade=t=in:st=0:d=${num(fadeIn)}`);
  chains.push(`${videoLabel}${tail.join(',')}[vout]`);

  // Audio: the clip's own track when it has one, silence otherwise.
  const audioSource = request.source.hasAudio ? `[${inputs.sourceIndex}:a]` : `[${inputs.silenceIndex}:a]`;
  const audioParts = ['aformat=sample_fmts=fltp:sample_rates=44100:channel_layouts=stereo'];
  const volume = clamp(request.volume ?? 1, 0, 4, 1);
  if (Math.abs(volume - 1) > 0.001) audioParts.push(`volume=${num(volume)}`);
  if (fadeIn > 0) audioParts.push(`afade=t=in:st=0:d=${num(fadeIn)}`);
  chains.push(`${audioSource}${audioParts.join(',')}[aout]`);

  const crf = Math.round(clamp(request.crf ?? 20, 0, 51, 20));
  const preset = request.preset ?? 'veryfast';

  return [
    '-nostdin',
    ...inputs.args,
    '-filter_complex',
    chains.join(';'),
    '-map',
    '[vout]',
    '-map',
    '[aout]',
    '-t',
    num(duration),
    '-c:v',
    'libx264',
    '-preset',
    preset,
    '-crf',
    String(crf),
    '-pix_fmt',
    'yuv420p',
    '-c:a',
    'aac',
    '-b:a',
    '192k',
    '-ar',
    '44100',
    '-ac',
    '2',
    request.output
  ];
};

